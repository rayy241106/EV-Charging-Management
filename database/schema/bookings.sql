CREATE TABLE BOOKINGS (
    BookingID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    UserID NUMBER NOT NULL,
    VehicleID NUMBER NOT NULL,
    ChargerID NUMBER NOT NULL,
    BookingDate DATE NOT NULL,
    StartTime DATE NOT NULL,
    EndTime DATE NOT NULL,
    Status VARCHAR2(20) NOT NULL,

    CONSTRAINT PK_BOOKINGS
        PRIMARY KEY (BookingID),

    CONSTRAINT FK_BOOKINGS_USER
        FOREIGN KEY (UserID)
        REFERENCES USERS(UserID),

    CONSTRAINT FK_BOOKINGS_VEHICLE
        FOREIGN KEY (VehicleID)
        REFERENCES VEHICLES(VehicleID),

    CONSTRAINT FK_BOOKINGS_CHARGER
        FOREIGN KEY (ChargerID)
        REFERENCES CHARGERS(ChargerID),

    CONSTRAINT CK_BOOKINGS_TIME
        CHECK (EndTime > StartTime),

    CONSTRAINT CK_BOOKINGS_STATUS
        CHECK (Status IN ('Pending', 'Confirmed', 'Completed', 'Cancelled'))
);
