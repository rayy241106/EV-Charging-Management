CREATE TABLE CHARGERS (
    ChargerID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    StationID NUMBER NOT NULL,
    ChargerNumber NUMBER NOT NULL,
    ChargerType VARCHAR2(30) NOT NULL,
    PowerOutput NUMBER(6,2) NOT NULL,
    PricePerKWh NUMBER(6,2) NOT NULL,
    Status VARCHAR2(20) NOT NULL,

    CONSTRAINT PK_CHARGERS
        PRIMARY KEY (ChargerID),

    CONSTRAINT FK_CHARGERS_STATION
        FOREIGN KEY (StationID)
        REFERENCES STATIONS(StationID),

    CONSTRAINT UQ_CHARGERS_NUMBER
        UNIQUE (StationID, ChargerNumber),

    CONSTRAINT CK_CHARGERS_TYPE
        CHECK (ChargerType IN ('AC', 'DC')),

    CONSTRAINT CK_CHARGERS_POWER
        CHECK (PowerOutput > 0),

    CONSTRAINT CK_CHARGERS_PRICE
        CHECK (PricePerKWh > 0),

    CONSTRAINT CK_CHARGERS_STATUS
        CHECK (Status IN ('Available', 'Occupied', 'Maintenance'))
);
