CREATE TABLE CHARGING_SESSIONS (
    SessionID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    BookingID NUMBER NOT NULL,
    StartTime DATE NOT NULL,
    EndTime DATE NOT NULL,
    UnitsConsumed NUMBER NOT NULL,
    TotalCost NUMBER NOT NULL,

    CONSTRAINT PK_CHARGING_SESSIONS
        PRIMARY KEY (SessionID),

    CONSTRAINT FK_CHARGING_SESSIONS_BOOKING
        FOREIGN KEY (BookingID)
        REFERENCES BOOKINGS(BookingID),

    CONSTRAINT CK_CHARGING_SESSIONS_TIME
        CHECK (EndTime > StartTime),

    CONSTRAINT CK_CHARGING_SESSIONS_UNITS
        CHECK (UnitsConsumed > 0),

    CONSTRAINT CK_CHARGING_SESSIONS_COST
        CHECK (TotalCost >= 0)
);
