CREATE TABLE MAINTENANCE_REPORTS (
    ReportID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    BookingID NUMBER NOT NULL,
    ChargerID NUMBER NOT NULL,
    UserID NUMBER NOT NULL,
    IssueType VARCHAR2(100) NOT NULL,
    Description VARCHAR2(500) NOT NULL,
    Status VARCHAR2(30) NOT NULL,
    ReportDate DATE NOT NULL,

    CONSTRAINT PK_MAINTENANCE_REPORTS
        PRIMARY KEY (ReportID),

    CONSTRAINT FK_MAINT_REPORTS_BOOKING
        FOREIGN KEY (BookingID)
        REFERENCES BOOKINGS(BookingID),

    CONSTRAINT FK_MAINT_REPORTS_CHARGER
        FOREIGN KEY (ChargerID)
        REFERENCES CHARGERS(ChargerID),

    CONSTRAINT FK_MAINT_REPORTS_USER
        FOREIGN KEY (UserID)
        REFERENCES USERS(UserID)
);
