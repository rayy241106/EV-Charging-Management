CREATE TABLE MAINTENANCE_VERIFICATION (
    VerificationID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ReportID NUMBER NOT NULL,
    UserID NUMBER NOT NULL,
    Result VARCHAR2(50) NOT NULL,
    Comments VARCHAR2(500),
    VerificationDate DATE NOT NULL,

    CONSTRAINT PK_MAINTENANCE_VERIFICATION
        PRIMARY KEY (VerificationID),

    CONSTRAINT FK_MAINT_VERIFICATION_REPORT
        FOREIGN KEY (ReportID)
        REFERENCES MAINTENANCE_REPORTS(ReportID),

    CONSTRAINT FK_MAINT_VERIFICATION_USER
        FOREIGN KEY (UserID)
        REFERENCES USERS(UserID),

    CONSTRAINT CK_MAINT_VERIFICATION_RESULT
        CHECK (Result IN ('Approved', 'Rejected', 'Pending'))
);
