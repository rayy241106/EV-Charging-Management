CREATE TABLE VEHICLES (
    VehicleID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    UserID NUMBER NOT NULL,
    VehicleNumber VARCHAR2(20) NOT NULL,
    VehicleModel VARCHAR(100) NOT NULL,
    VehicleType VARCHAR(30) NOT NULL,
    BatteryCapacity NUMBER(6,2) NOT NULL,

    CONSTRAINT PK_VEHICLES PRIMARY KEY (VehicleID),

    CONSTRAINT FK_VEHICLES_USER
        FOREIGN KEY (UserID)
        REFERENCES USERS(UserID),

    CONSTRAINT UQ_VEHICLES_NUMBER
        UNIQUE (VehicleNumber),

    CONSTRAINT CK_VEHICLES_TYPE
        CHECK (VehicleType IN ('Car', 'Bike', 'Bus', 'Other')),

    CONSTRAINT CK_VEHICLES_BATTERY
        CHECK (BatteryCapacity > 0)
);
